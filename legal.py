"""Тексты документов для кнопок в боте.

Персональные данные не хранятся в репозитории: они подставляются из переменных
окружения на хосте. Если переменная не задана, в тексте пишется нейтральная
формулировка — плейсхолдеры в интерфейс не попадают.
"""

import html
import os

NAME = os.getenv("LEGAL_NAME", "").strip()
INN = os.getenv("LEGAL_INN", "").strip()
EMAIL = os.getenv("SUPPORT_EMAIL", "").strip()
TG = os.getenv("SUPPORT_TG", "").strip()


def _safe(value: str) -> str:
    return html.escape(value)


def _seller() -> str:
    parts = []
    if NAME:
        parts.append(_safe(NAME))
    if INN:
        parts.append(f"ИНН {_safe(INN)}")
    return ", ".join(parts) or "данные продавца указаны в чеке"


def _contacts() -> str:
    lines = []
    if EMAIL:
        lines.append(f"Почта: {_safe(EMAIL)}")
    if TG:
        lines.append(f"Telegram: {_safe(TG)}")
    return "\n".join(lines) or "Связаться можно через поддержку в боте."


