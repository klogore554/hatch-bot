use crate::telegram::escape_html;
use std::env;

fn env_html(name: &str) -> String {
    escape_html(&env::var(name).unwrap_or_default())
}

fn seller() -> String {
    let name = env_html("LEGAL_NAME");
    let inn = env_html("LEGAL_INN");
    let mut parts = Vec::new();
    if !name.is_empty() {
        parts.push(name);
    }
    if !inn.is_empty() {
        parts.push(format!("ИНН {}", inn));
    }
    if parts.is_empty() {
        "данные продавца указаны в чеке".to_string()
    } else {
        parts.join(", ")
    }
}

fn contacts() -> String {
    let mut lines = Vec::new();
    let email = env_html("SUPPORT_EMAIL");
    let tg = env_html("SUPPORT_TG");
    if !email.is_empty() {
        lines.push(format!("Почта: {}", email));
    }
    if !tg.is_empty() {
        lines.push(format!("Telegram: {}", tg));
    }
    if lines.is_empty() {
        "Связаться можно через поддержку в боте.".to_string()
    } else {
        lines.join("\n")
    }
}

pub fn offer() -> String {
    format!(
        "<b>Оферта на оказание услуг</b>\n\n\
         Продавец: {}.\n\
         Услуга — доступ к расширенным возможностям бота: безлимитные привычки, статистика, серии и групповой челлендж.\n\n\
         Стоимость: 299 ₽ в месяц. Оплата производится через платёжный сервис по ссылке в боте. Доступ активируется автоматически после подтверждения оплаты и действует 30 дней.\n\n\
         Подписка рекуррентная: списание на следующий месяц производится платёжным сервисом по согласию пользователя. Отключить продление можно у поддержки.\n\n\
         Услуга предоставляется в цифровом виде внутри бота сразу после активации.\n\n\
         Поддержка:\n{}",
        seller(),
        contacts()
    )
}

pub fn refund() -> String {
    format!(
        "<b>Условия возврата</b>\n\n\
         Если оплата прошла, а доступ не открылся в течение 24 часов — напиши в поддержку. Деньги вернут в полном объёме.\n\n\
         Если доступ был активирован, возврат за неиспользованный период рассматривается индивидуально в течение 7 дней с момента оплаты.\n\n\
         Для возврата укажи номер заказа из платёжного сервиса и способ оплаты. Средства возвращаются на тот же способ.\n\n\
         Поддержка:\n{}",
        contacts()
    )
}

pub fn privacy() -> String {
    format!(
        "<b>Политика обработки данных</b>\n\n\
         Бот хранит идентификатор Telegram, имя пользователя, источник запуска, названия привычек, отметки и срок доступа. Адрес email для чека передаётся платёжному сервису и в базе бота не сохраняется.\n\n\
         Данные используются только для работы бота: напоминаний, серий, реферальной механики и учёта оплаты. Сторонним сервисам данные не передаются, за исключением платёжного сервиса при оформлении подписки.\n\n\
         Удалить свои данные можно по запросу в поддержку.\n\n\
         Поддержка:\n{}",
        contacts()
    )
}

pub fn get(name: &str) -> Option<String> {
    match name {
        "doc_offer" => Some(offer()),
        "doc_refund" => Some(refund()),
        "doc_privacy" => Some(privacy()),
        _ => None,
    }
}
